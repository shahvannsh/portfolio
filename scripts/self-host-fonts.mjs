// Downloads the site's Google Fonts once and serves them from your own domain, so the pages need no third-party
// requests at all (better privacy + a tighter Content-Security-Policy). Needs internet access once.
//
//   npm run fonts
//
// It writes public/fonts/*.woff2 and public/fonts/fonts.css, swaps the Google <link> tags in index.html and
// card.html for /fonts/fonts.css, and removes fonts.googleapis.com / fonts.gstatic.com from vercel.json's CSP.
// Safe to run again. Options: --root <dir>  --css-base <url>  --subsets latin,latin-ext  --no-patch
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const opt = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const root = resolve(opt("--root", join(dirname(fileURLToPath(import.meta.url)), "..")));
const cssBase = opt("--css-base", "https://fonts.googleapis.com/css2");
const subsets = new Set(opt("--subsets", "latin").split(","));
const patch = !args.includes("--no-patch");

const QUERY =
  "family=Orbitron:wght@500;600;700;800;900&family=Space+Grotesk:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;500;600&display=swap";
// A modern browser user agent makes Google answer with compact woff2 files.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, text) => writeFileSync(join(root, p), text);

async function main() {
  const cssResponse = await fetch(`${cssBase}?${QUERY}`, { headers: { "User-Agent": UA } });
  if (!cssResponse.ok) throw new Error(`Could not fetch the font CSS (${cssResponse.status})`);
  const css = await cssResponse.text();

  const blocks = [...css.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/gi)].map((m) => ({ subset: m[1], body: m[2] }));
  if (!blocks.length) throw new Error("No @font-face rules found in the response.");

  mkdirSync(join(root, "public/fonts"), { recursive: true });
  const saved = new Map(); // remote url -> local file name
  const rules = [];

  for (const { subset, body } of blocks) {
    if (!subsets.has(subset)) continue;
    const get = (prop) => new RegExp(`${prop}:\\s*([^;]+);`, "i").exec(body)?.[1].trim();
    const family = get("font-family")?.replace(/['"]/g, "");
    const url = /url\(([^)]+)\)/.exec(body)?.[1].replace(/['"]/g, "");
    if (!family || !url) continue;

    if (!saved.has(url)) {
      const file = `${slug(family)}-${subset}-${createHash("sha1").update(url).digest("hex").slice(0, 8)}.woff2`;
      const font = await fetch(url, { headers: { "User-Agent": UA } });
      if (!font.ok) throw new Error(`Could not download ${url} (${font.status})`);
      writeFileSync(join(root, "public/fonts", file), Buffer.from(await font.arrayBuffer()));
      saved.set(url, file);
    }
    const range = get("unicode-range");
    rules.push(
      `/* ${family} ${subset} */\n@font-face {\n  font-family: "${family}";\n  font-style: ${get("font-style") ?? "normal"};\n  font-weight: ${get("font-weight") ?? "400"};\n  font-display: swap;\n  src: url("/fonts/${saved.get(url)}") format("woff2");${range ? `\n  unicode-range: ${range};` : ""}\n}`,
    );
  }
  if (!rules.length) throw new Error(`No rules for subsets: ${[...subsets].join(", ")}`);
  write("public/fonts/fonts.css", `/* Self-hosted Google Fonts (generated by scripts/self-host-fonts.mjs). Licences: SIL Open Font License. */\n\n${rules.join("\n\n")}\n`);
  console.log(`Saved ${saved.size} font file(s) and ${rules.length} @font-face rules to public/fonts/`);

  if (!patch) return;

  for (const page of ["index.html", "card.html"]) {
    const nl = read(page).includes("\r\n") ? "\r\n" : "\n";
    let html = read(page).replace(/\r\n/g, "\n");
    if (!html.includes("/fonts/fonts.css")) {
      html = html.replace(/[ \t]*<link[^>]*rel="preconnect"[^>]*fonts\.g(oogleapis|static)\.com[^>]*>\n?/g, "");
      html = html.replace(/<link[^>]*href="https:\/\/fonts\.googleapis\.com[^"]*"[^>]*>/, '<link rel="stylesheet" href="/fonts/fonts.css" />');
    }
    write(page, html.replace(/\n/g, nl));
  }

  const cfg = JSON.parse(read("vercel.json"));
  for (const group of cfg.headers ?? []) {
    for (const h of group.headers) {
      if (h.key !== "Content-Security-Policy") continue;
      h.value = h.value
        .split(";")
        .map((d) => d.trim())
        .map((d) => (d.startsWith("style-src ") ? "style-src 'self'" : d.startsWith("font-src ") ? "font-src 'self'" : d))
        .join("; ");
    }
  }
  write("vercel.json", JSON.stringify(cfg, null, 2) + "\n");
  console.log("Updated index.html, card.html and the CSP in vercel.json. Commit the new files in public/fonts/.");
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
